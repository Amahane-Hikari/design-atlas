import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createProject,createBlock,BLOCKS} from '../dist/engine.js';
import {searchStudio,replacementOptions,replaceProjectBlock,writeWorkspaceAtomically} from '../dist/studio-model.js';
let assertions=0;const check=(condition,message)=>{assert.ok(condition,message);assertions++;};
const items=[{id:'a',name:'Grid system',kind:'reference',tags:['布局'],description:'Design grid'},{id:'b',name:'Grid',kind:'block',tags:['布局'],description:'Feature cards'},{id:'c',name:'个人主页',kind:'site',summary:'开发者的作品与文章'},{id:'d',name:'Pricing',kind:'block',tags:['价格','商业']}];
const original=structuredClone(items);
let stored=null,queue=Promise.resolve();const storage={getItem:()=>stored,setItem:(key,value)=>{stored=value}};
const locks={request(name,options,fn){const result=queue.then(fn);queue=result.catch(()=>{});return result;}};
const writes=await Promise.allSettled([writeWorkspaceAtomically(storage,locks,'test',null,'one'),writeWorkspaceAtomically(storage,locks,'test',null,'two')]);
check(writes.filter(x=>x.status==='fulfilled').length===1,'two stale tabs cannot both commit');
check(writes.filter(x=>x.status==='rejected').length===1&&stored==='one','stale tab is rejected instead of losing saved data');
await writeWorkspaceAtomically(storage,locks,'test','one','one-and-two');
check(stored==='one-and-two','retry after reloading library can commit');
await assert.rejects(writeWorkspaceAtomically(storage,null,'test','one-and-two','bad'));assertions++;
check(stored==='one-and-two','unsupported locking never writes unsafely');
await assert.rejects(writeWorkspaceAtomically({getItem:()=>null,setItem(){throw Error('quota')}},locks,'quota',null,'test'));assertions++;
check(searchStudio(items,'grid')[0].id==='b','exact title outranks prefix and description');
check(searchStudio(items,'布局 grid').length===2,'tokens use intersection across metadata');
check(searchStudio(items,'开发者')[0].id==='c','website summaries are searchable');
check(searchStudio(items,'价格','block')[0].id==='d','Chinese tags match');
check(searchStudio(items,'grid','site').length===0,'kind filter is intersected with query');
check(searchStudio(items,'','all',2).length===2,'result limit');
check(JSON.stringify(original)===JSON.stringify(items),'search never mutates source list');
check(searchStudio(items,'unknown').length===0,'empty matches stay empty');
check(searchStudio(items,'   GRID ').length===2,'case and surrounding whitespace ignored');
check(replacementOptions('missing').length===0,'unknown module has no replacements');
const p=createProject();p.blocks=[createBlock('hero-editorial'),createBlock('footer')];p.blocks[0].props.title='保留我的主标题';p.blocks[0].hidden=true;p.customCSS='body { letter-spacing: 1px; }';
const before=structuredClone(p),alternative=replacementOptions('hero-editorial')[0];
check(!!alternative,'hero category has alternate layouts');
const after=replaceProjectBlock(p,p.blocks[0].uid,alternative.id);
check(after.blocks[0].type===alternative.id,'switches the selected module only');
check(after.blocks[0].props.title==='保留我的主标题','preserves shared text');
check(after.blocks[0].uid===p.blocks[0].uid&&after.blocks[1].uid===p.blocks[1].uid,'preserves selection and other IDs');
check(after.blocks[0].hidden===true,'preserves hidden state');
check(JSON.stringify(after.blocks[1])===JSON.stringify(p.blocks[1]),'preserves neighboring blocks');
check(after.customCSS===p.customCSS&&JSON.stringify(after.theme)===JSON.stringify(p.theme),'preserves project styling');
check(JSON.stringify(p)===JSON.stringify(before),'replace does not mutate original');
assert.throws(()=>replaceProjectBlock(p,'missing',alternative.id));assertions++;
assert.throws(()=>replaceProjectBlock(p,p.blocks[0].uid,'footer'));assertions++;
for(const block of BLOCKS)check(replacementOptions(block.id).every(x=>x.category===block.category&&x.id!==block.id),'replacement category '+block.id);
const offline=await readFile(new URL('../dist/offline.html',import.meta.url),'utf8');
check(offline.includes('createStudioUI')&&offline.includes('saveWorkspaceProject'),'offline bundle contains studio modules');
check(!/<link[^>]+href="studio.css"/.test(offline),'studio styling is embedded offline');
console.log(JSON.stringify({status:'PASS',assertions,scope:'global search, layout replacement, offline integration'},null,2));
